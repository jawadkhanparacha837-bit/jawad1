/**
 * Haversine formula to compute accurate straight-line distance in kilometers
 * between two verified geographic coordinates.
 */
export function calculateDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
      Math.cos(lat2 * (Math.PI / 180)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
}

/**
 * Finds the closest supported Pakistan city to a given GPS coordinate
 */
export function findClosestCity(lat: number, lon: number): { city: CityInfo; distanceKm: number } {
  let closest = PAKISTAN_CITIES[0];
  let minDistance = calculateDistanceKm(lat, lon, closest.lat, closest.lon);

  for (const city of PAKISTAN_CITIES) {
    const dist = calculateDistanceKm(lat, lon, city.lat, city.lon);
    if (dist < minDistance) {
      minDistance = dist;
      closest = city;
    }
  }

  return { city: closest, distanceKm: minDistance };
}

/**
 * Evaluates whether a facility is currently open based on verified 24/7 status
 * or published operating hours in Pakistan Standard Time (UTC+5).
 */
export function isFacilityOpenNow(fac: HealthcareFacility): boolean | null {
  if (fac.is24Hours || fac.hasEmergency) return true;
  if (!fac.openHours) return null;

  const hoursLower = fac.openHours.toLowerCase();
  if (hoursLower.includes('24 hours') || hoursLower.includes('24/7')) {
    return true;
  }

  // Parse standard pattern like "08:00 AM – 11:00 PM" or "09:00 AM – 09:00 PM"
  const match = fac.openHours.match(/(\d{1,2}):(\d{2})\s*(AM|PM)\s*[–-]\s*(\d{1,2}):(\d{2})\s*(AM|PM)/i);
  if (!match) return null;

  const toMinutes = (hStr: string, mStr: string, mer: string) => {
    let h = parseInt(hStr, 10);
    const m = parseInt(mStr, 10);
    const isPm = mer.toUpperCase() === 'PM';
    if (h === 12) h = isPm ? 12 : 0;
    else if (isPm) h += 12;
    return h * 60 + m;
  };

  const startMins = toMinutes(match[1], match[2], match[3]);
  let endMins = toMinutes(match[4], match[5], match[6]);
  if (endMins === 0) endMins = 24 * 60; // 12:00 AM midnight

  // Current time in Pakistan (UTC+5)
  const now = new Date();
  const utcMs = now.getTime() + now.getTimezoneOffset() * 60000;
  const pktDate = new Date(utcMs + 5 * 3600000);
  const currentMins = pktDate.getHours() * 60 + pktDate.getMinutes();

  return currentMins >= startMins && currentMins <= endMins;
}

/**
 * Multi-factor composite ranking score based on:
 * - Breadth of verified medical specialties & emergency capability
 * - Verified public rating & review count (log-weighted so a small sample doesn't dominate)
 * - Data completeness (verified phone, website, OPD timings, coordinates)
 */
export function computeFacilityQualityScore(fac: HealthcareFacility): number {
  let score = 0;

  // 1. Medical Services & Emergency Capability (up to 40 pts)
  if (fac.hasEmergency) score += 18;
  score += Math.min(22, (fac.specialties?.length || 0) * 3.5);

  // 2. Verified Rating & Review Volume (up to 40 pts)
  if (fac.rating && fac.reviewCount) {
    const ratingScore = (fac.rating / 5) * 25;
    const volumeConfidence = Math.min(15, Math.log10(fac.reviewCount + 1) * 4);
    score += ratingScore + volumeConfidence;
  }

  // 3. Data Completeness & Traceability (up to 20 pts)
  if (fac.phone) score += 5;
  if (fac.website) score += 5;
  if (fac.opdTimings) score += 5;
  if (fac.lat !== undefined && fac.lon !== undefined) score += 5;

  return Math.round(score * 10) / 10;
}

/**
 * Returns emergency contacts appropriate for a given city
 */
export function getEmergencyContactsForCity(city: SupportedCity | 'All'): EmergencyContactItem[] {
  if (city === 'All') return VERIFIED_EMERGENCY_CONTACTS;
  return VERIFIED_EMERGENCY_CONTACTS.filter(
    item => item.cities.includes('All') || item.cities.includes(city)
  );
}
